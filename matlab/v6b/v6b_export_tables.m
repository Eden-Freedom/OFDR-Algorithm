function v6b_export_tables(results,cfg)
%V6B_EXPORT_TABLES 全部 trial 数据、失败率、汇总统计保留 CSV。
    folder=cfg.v6b.output_dir;
    if ~exist(folder,'dir'),mkdir(folder);end
    C=results.correlation;S=results.sswt;A=results.components;G=results.spatial;
    fid=open_file(fullfile(folder,'V6b_correlation_trials.csv'));
    fprintf(fid,['trial,rho_target,rho_empirical,scatter_seed,error_seed_ref,' ...
        'error_seed_meas,valid,diff_rmse_MHz,gauge_rmse_rad,proxy_rmse_ue,' ...
        'common_gauge_rmse_rad,common_proxy_rmse_ue,valid_fraction,' ...
        'common_valid_fraction,weighted_mean_diff_MHz,scale_ppm,' ...
        'nonlinear_diff_rmse_MHz,near_wrap_count,failure_reason\n']);
    for j=1:C.repeats
        for i=1:numel(C.rho_target)
            fprintf(fid,'%d,%.6f,%.9g,%d,%d,%d,%d,%.10g,%.10g,%.10g,%.10g,%.10g,%.10g,%.10g,%.10g,%.10g,%.10g,%.10g,"%s"\n', ...
                j,C.rho_target(i),C.empirical_rho(i,j), ...
                C.scatter_seed(j),C.error_seed_ref(j),C.error_seed_meas(j),C.valid(i,j), ...
                C.diff_rmse_MHz(i,j),C.gauge_rmse_rad(i,j),C.false_proxy_rmse_microeps(i,j), ...
                C.common_gauge_rmse_rad(i,j),C.common_false_proxy_rmse_microeps(i,j), ...
                C.valid_fraction(i,j),C.common_valid_fraction(i,j), ...
                C.diff_weighted_mean_MHz(i,j),C.diff_scale_ppm(i,j), ...
                C.diff_nonlinear_rmse_MHz(i,j),C.near_wrap_count(i,j), ...
                safe_str(C.failure_reason{i,j}));
        end
    end
    fclose(fid);
    fid=open_file(fullfile(folder,'V6b_correlation_summary.csv'));
    fprintf(fid,'rho,n_success,n_trials,failure_rate,matched_failure_rate,mean_diff_MHz,mean_gauge_rad,mean_proxy_ue,bootstrap_CI95_low_ue,bootstrap_CI95_high_ue,paired_delta_vs_rho1_mean_ue,paired_delta_CI95_low_ue,paired_delta_CI95_high_ue\n');
    for i=1:numel(C.rho_target)
        m=C.summary;
        fprintf(fid,'%.6f,%d,%d,%.10g,%.10g,%.10g,%.10g,%.10g,%.10g,%.10g,%.10g,%.10g,%.10g\n', ...
            C.rho_target(i),m.n_success(i),C.repeats,m.failure_rate(i),m.matched_failure_rate(i), ...
            m.mean_diff_MHz(i),m.mean_gauge_rad(i),m.mean_proxy_microeps(i), ...
            m.proxy_CI95_microeps(i,1),m.proxy_CI95_microeps(i,2), ...
            m.paired_vs_rho1_mean_microeps(i),m.paired_vs_rho1_CI95_microeps(i,1), ...
            m.paired_vs_rho1_CI95_microeps(i,2));
    end
    fclose(fid);
    fid=open_file(fullfile(folder,'V6b_independent_SSWT_trials.csv'));
    fprintf(fid,'trial,seed_reference,seed_measurement,scatter_seed,valid,ref_rmse_MHz,meas_rmse_MHz,diff_rmse_MHz,gauge_rmse_rad,proxy_rmse_ue,valid_fraction,near_wrap_count,failure_reason\n');
    for j=1:S.repeats
        fprintf(fid,'%d,%d,%d,%d,%d,%.10g,%.10g,%.10g,%.10g,%.10g,%.10g,%.10g,"%s"\n', ...
            j,S.aux_seed_ref(j),S.aux_seed_meas(j),S.scatter_seed(j),S.valid(j), ...
            S.reference_rmse_MHz(j),S.measurement_rmse_MHz(j),S.diff_rmse_MHz(j), ...
            S.gauge_rmse_rad(j),S.false_proxy_rmse_microeps(j), ...
            S.valid_fraction(j),S.near_wrap_count(j),safe_str(S.failure_reason{j}));
    end
    fclose(fid);
    fid=open_file(fullfile(folder,'V6b_component_ablation.csv'));
    fprintf(fid,'case,valid,diff_rmse_MHz,gauge_rmse_rad,proxy_rmse_ue,valid_fraction,failure_reason\n');
    for j=1:numel(A.case_order)
        fprintf(fid,'%s,%d,%.10g,%.10g,%.10g,%.10g,"%s"\n', ...
            A.case_order{j},A.case_valid(j),A.diff_rmse_MHz(j),A.gauge_rmse_rad(j), ...
            A.false_proxy_rmse_microeps(j),A.valid_fraction(j),safe_str(A.failure_reason{j}));
    end
    fclose(fid);
    fid=open_file(fullfile(folder,'V6b_distance_gauge_matrix.csv'));
    fprintf(fid,'distance_low_m,distance_high_m,gauge_requested_mm,gauge_actual_mm,gauge_rmse_rad,proxy_rmse_ue,valid_fraction,valid_count,failure_reason\n');
    for j=1:numel(G.gauge_requested_mm)
        for k=1:size(G.distance_bands_m,1)
            fprintf(fid,'%.5f,%.5f,%.6f,%.6f,%.10g,%.10g,%.10g,%d,"%s"\n', ...
                G.distance_bands_m(k,1),G.distance_bands_m(k,2), ...
                G.gauge_requested_mm(j),G.gauge_actual_mm(j),G.gauge_rmse_rad(j,k), ...
                G.false_proxy_rmse_microeps(j,k),G.valid_fraction(j,k),G.valid_count(j,k), ...
                safe_str(G.failure_reason{j,k}));
        end
    end
    fclose(fid);
end
function fid=open_file(path)
    fid=fopen(path,'w');
    if fid<0,error('V6b:CSVWrite','无法创建 %s',path);end
end
function s=safe_str(x)
    if isempty(x),s='';return;end
    s=strrep(x,char(34),char(39));
    s=strrep(s,sprintf('\n'),' ');
    s=strrep(s,sprintf('\r'),' ');
end
