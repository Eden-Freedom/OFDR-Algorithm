function v6c_export_tables(cfg,results)
%V6C_EXPORT_TABLES 保存所有工况的准确数值和失败原因，不只保存图像。
    folder=cfg.v6c.output_dir;
    if ~exist(folder,'dir'),mkdir(folder);end
    fid=fopen(fullfile(folder,'V6c_strain_sweep.csv'),'wt');
    if fid<0,error('V6c:IO','无法写入应变结果 CSV');end
    fprintf(fid,['strain_input_microeps,method,valid,core_truth_microeps,core_measured_microeps,' ...
       'core_rmse_microeps,core_bias_microeps,static_false_rmse_microeps,' ...
       'global_rmse_microeps,gauge_phase_rmse_rad,valid_fraction,core_valid_fraction,' ...
       'calibration_difference_rmse_MHz,failure_reason\n']);
    for i=1:numel(results.strain_tests)
        trial=results.strain_tests{i}.trial;
        for j=1:numel(trial.order)
            c=trial.cases.(trial.order{j});
            if ~isempty(c.metrics)
                m=c.metrics;
                fprintf(fid,'%.8g,%s,%d,%.8g,%.8g,%.8g,%.8g,%.8g,%.8g,%.8g,%.8g,%.8g,%.8g,%s\n', ...
                    results.strain_tests{i}.strain_microeps,trial.order{j},c.valid, ...
                    m.core_true_mean_microeps,m.core_measured_mean_microeps, ...
                    m.core_strain_rmse_microeps,m.core_bias_microeps, ...
                    m.static_false_strain_rmse_microeps,m.full_strain_rmse_microeps, ...
                    m.full_gauge_phase_rmse_rad,m.valid_fraction,m.core_valid_fraction, ...
                    c.calibration_difference_rmse_MHz,strrep(c.failure_reason,',',';'));
            else
                fprintf(fid,'%.8g,%s,0,NaN,NaN,NaN,NaN,NaN,NaN,NaN,NaN,NaN,%.8g,%s\n', ...
                    results.strain_tests{i}.strain_microeps,trial.order{j}, ...
                    c.calibration_difference_rmse_MHz,strrep(c.failure_reason,',',';'));
            end
        end
    end
    fclose(fid);
    if isfield(results,'mc')
        out=results.mc;
        fid=fopen(fullfile(folder,'V6c_strain_MC.csv'),'wt');
        if fid<0,error('V6c:IO','无法写入 MC CSV');end
        fprintf(fid,'trial,scatter_seed,aux_ref_seed,aux_meas_seed,valid,oracle_core_rmse_ue,sswt_core_rmse_ue,oracle_static_rmse_ue,sswt_static_rmse_ue,valid_fraction,failure_reason\n');
        for k=1:numel(out.valid)
            fprintf(fid,'%d,%d,%d,%d,%d,%.9g,%.9g,%.9g,%.9g,%.9g,%s\n',k, ...
                out.seed_scatter(k),out.seed_ref(k),out.seed_meas(k),out.valid(k), ...
                out.oracle_core_rmse(k),out.sswt_core_rmse(k), ...
                out.oracle_static_rmse(k),out.sswt_static_rmse(k), ...
                out.valid_fraction(k),strrep(out.failure_reason{k},',',';'));
        end
        fclose(fid);
    end
end
