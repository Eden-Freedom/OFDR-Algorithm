function v7b_export_csv(folder,out,filename)
%V7B_EXPORT_CSV 每行一个 trial，保存成功/失败分母和可追溯随机种子。
    if ~exist(folder,'dir'),mkdir(folder);end
    fid=fopen(fullfile(folder,filename),'w');
    if fid<0,error('V7b:CSV','无法写入试次CSV');end
    cl=onCleanup(@()fclose(fid));
    fprintf(fid,['trial,scatter_seed,ref_seed,meas_seed,success,', ...
        'core_oracle,core_sswt,core_smoothed,core_affine,core_sapc,', ...
        'holdout_sswt,holdout_affine,holdout_sapc,', ...
        'valid_sswt,valid_affine,valid_sapc,', ...
        'train_phase_before_rad,train_phase_after_rad,', ...
        'train_count,hessian_rcond,data_hessian_rcond,jacobian_rank,', ...
        'beta_l2_MHz,correction_peak_MHz,', ...
        'diff_q_rmse_MHz,aux_ref_rmse_MHz,aux_meas_rmse_MHz,', ...
        'failure_id,failure_reason\n']);
    n=out.n_trials;
    for k=1:n
        a=[k,out.seed_scatter(k),out.seed_ref(k),out.seed_meas(k),out.success(k), ...
           out.core_rmse(k,:),out.static_holdout(k,[2 4 5]), ...
           out.valid_fraction(k,[2 4 5]), ...
           out.training_before(k),out.training_after(k),out.train_count(k), ...
           out.hessian_rcond(k),out.data_hessian_rcond(k),out.jacobian_rank(k), ...
           out.beta_l2_MHz(k),out.max_correction_MHz(k), ...
           out.diff_rmse_MHz(k),out.aux_ref_rmse_MHz(k),out.aux_meas_rmse_MHz(k)];
        fprintf(fid,'%.12g,',a);
        id=out.failure_id{k};reason=out.failure_reason{k};
        if isempty(id),id='';end;if isempty(reason),reason='';end
        % CSV 用双引号转义引号，不丢失失败原因；换行改为空格。
        id=strrep(strrep(id,'"','""'),sprintf('\n'),' ');
        reason=strrep(strrep(strrep(reason,'"','""'),sprintf('\n'),' '),sprintf('\r'),' ');
        fprintf(fid,'"%s","%s"\n',id,reason);
    end
end
