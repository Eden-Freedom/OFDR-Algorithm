function smoke_test_v7c_size_gate_audit()
%SMOKE_TEST_V7C_SIZE_GATE_AUDIT 纯合成表格检验，不调用任何 Rayleigh/SSWT/NUFFT。
% 保持 V7c 原协议不变；本测试不运行冻结种子。
    cfg=config_v7c();
    r=struct();
    r.n_trials=4;
    r.success=[true;true;true;false];
    r.chosen_alpha=[0;1;0;NaN];
    r.extra_peak_MHz=[1.2;0.5;0.7;NaN];
    r.cv_folds_ok=[false;true;true;false];
    r.fallback_reason={'non-affine correction size gate'; ...
        'CV accepted non-affine blend';'CV selected affine';''};
    r.core_rmse=[0.10 0.4 0.3 0.25 0.20 0.25; ...
                 0.10 0.4 0.3 0.30 0.28 0.28; ...
                 0.10 0.4 0.3 0.22 0.24 0.22; ...
                 NaN NaN NaN NaN NaN NaN];
    r.holdout_rmse=[0.01 0.4 0.3 0.33 0.23 0.33; ...
                    0.01 0.4 0.3 0.35 0.31 0.31; ...
                    0.01 0.4 0.3 0.25 0.28 0.25; ...
                    NaN NaN NaN NaN NaN NaN];
    results=struct('development',r);
    [T,a]=v7c_audit_size_gate_dev(results,cfg);
    assert(height(T)==4 && a.n_success==3 && a.n_early_refused==1, ...
        'V7c:SizeGateCounts','预筛选失败试次/回退次数错误');
    assert(a.n_refused_but_full_core_better==1 && ...
           a.n_refused_but_full_holdout_better==1, ...
        'V7c:SizeGateGain','Full 的事后收益计算错误');
    assert(T.early_refused(1) && ~T.cv_folds_ok(1), ...
        'V7c:SizeGateOrder','早期硬门控应发生在CV验证前');
    assert(isequal(a.refused_candidates_cell{1},[0 .25 .5]), ...
        'V7c:SizeGateFeasible','仅幅度上限的候选集合错误');
    assert(~T.success(4) && isnan(T.full_core_adv_vs_affine(4)), ...
        'V7c:SizeGateFail','失败试次不能被改写成零收益');
    fprintf('[V7c size-gate audit unit] PASS: hard precheck, candidate-size bounds, failures.\n');
end
