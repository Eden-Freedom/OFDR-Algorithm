function v7c_export_trials(folder,r,filename)
%V7C_EXPORT_TRIALS 保存全部成功及失败试次，不能选择性删除退化记录。
    if ~exist(folder,'dir'),mkdir(folder);end
    fid=fopen(fullfile(folder,filename),'w');
    if fid<0,error('V7c:Save','CSV 无法写入');end
    cleaner=onCleanup(@()fclose(fid));
    fprintf(fid,['trial,success,scatter_seed,ref_seed,meas_seed,', ...
        'oracle_core,raw_core,smooth_core,affine_core,full_sapc_core,adaptive_core,', ...
        'raw_holdout,affine_holdout,full_holdout,adaptive_holdout,', ...
        'raw_valid,affine_valid,full_valid,adaptive_valid,', ...
        'chosen_alpha,fallback,cv_folds_ok,cv_affine_rad,cv_best_rad,cv_gain_rad,cv_gain_frac,', ...
        'hessian_data_rcond,jacobian_rank,train_gauges,extra_peak_MHz,', ...
        'differential_q_RMSE_MHz,train_phase_gain_rad,core_common_count,holdout_common_count,', ...
        'gate_reason,failure_id,failure_reason\n']);
    for k=1:r.n_trials
        x=[k,r.success(k),r.seed_scatter(k),r.seed_ref(k),r.seed_meas(k), ...
            r.core_rmse(k,:),r.holdout_rmse(k,[2 4 5 6]), ...
            r.valid_fraction(k,[2 4 5 6]), ...
            r.chosen_alpha(k),r.fallback(k),r.cv_folds_ok(k), ...
            r.cv_affine_rad(k),r.cv_best_rad(k),r.cv_gain_rad(k),r.cv_gain_fraction(k), ...
            r.data_hessian_rcond(k),r.jacobian_rank(k),r.train_count(k),r.extra_peak_MHz(k), ...
            r.diff_q_rmse_MHz(k),r.train_phase_gain_rad(k), ...
            r.common_core_count(k),r.common_holdout_count(k)];
        fprintf(fid,'%.12g,',x);
        strings={r.fallback_reason{k},r.failure_id{k},r.failure_reason{k}};
        for j=1:3
            t=strings{j};if isempty(t),t='';end
            t=strrep(strrep(strrep(t,'"','""'),sprintf('\n'),' '),sprintf('\r'),' ');
            if j<3,fprintf(fid,'"%s",',t);else,fprintf(fid,'"%s"\n',t);end
        end
    end
end
