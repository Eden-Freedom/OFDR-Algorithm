function smoke_test_v7d_coverage_audit()
%SMOKE_TEST_V7D_COVERAGE_AUDIT 用完全合成的结果检查只读开发覆盖率统计。
% 不调用物理仿真，不读取原V7c/V7d盲测数据，也不生成随机试次。
    r=struct();
    r.dataset='development';
    r.n_trials=3;
    r.success=[true;true;false];
    r.alpha_v7c=[0;1;NaN];
    r.alpha_v7d=[.5;1;NaN];
    r.full_extra_peak_MHz=[1.2;.6;NaN];
    r.core_rmse=[.1 .4 .35 .32 .27 .30 .28; ...
                 .1 .45 .38 .35 .30 .31 .31; ...
                 nan(1,7)];
    r.holdout_rmse=[.01 .42 .40 .38 .32 .37 .35; ...
                    .01 .46 .43 .40 .35 .36 .36; ...
                    nan(1,7)];
    r.valid_fraction=[repmat(.91,1,7);repmat(.85,1,7);nan(1,7)];
    r.common_valid_fraction=[.5;.7;NaN];
    r.common_core_count=[30;40;NaN];
    r.common_holdout_count=[50;60;NaN];
    r.cv_folds_v7c=[false;true;false];
    r.cv_folds_v7d=[true;true;false];
    r.full_candidate_ok=[true true true false false; ...
                         true true true true true; ...
                         false(1,5)];
    r.fold_candidate_ok=[true true true false false; ...
                         true true true true true; ...
                         false(1,5)];
    r.reason_v7c={'non-affine correction size gate';'CV accepted non-affine blend';[]};
    r.reason_v7d={'CV accepted feasible non-affine candidate'; ...
                  'CV accepted feasible non-affine candidate';[]};
    results=struct('development',r);
    cfg=config_v7d();
    [T,d]=v7d_audit_coverage_dev(results,cfg);
    assert(height(T)==3 && d.n_success==2 && d.n_failure==1, ...
        'V7d:CoverageCounts','失败试次没有保留在分母。');
    assert(d.n_over_extra_limit==1 && d.n_changed==1, ...
        'V7d:CoverageBoundary','E超限或alpha变化检测错误。');
    assert(abs(d.E_max_MHz-1.2)<1e-12 && abs(d.E_min_MHz-.6)<1e-12, ...
        'V7d:CoverageE','E范围计算有误。');
    assert(abs(d.mean_common_valid-.6)<1e-12 && ...
           d.mean_core_common_count==35 && ...
           d.mean_holdout_common_count==55, ...
        'V7d:CoverageGauge','共同Gauge统计错误。');
    assert(d.n_Core_nonzero_gain==1 && d.n_Holdout_nonzero_gain==1, ...
        'V7d:CoveragePairing','逐trial配对增益未正确读取。');
    assert(~T.success(3) && isnan(T.core_gain_vs_v7c(3)) && ...
           ~T.changed(3), ...
        'V7d:CoverageFailure','失败trial不应成为成功或配对零收益。');
    fprintf('[V7d development coverage unit] PASS: E exposure, alpha decisions, common masks, failures.\n');
end
