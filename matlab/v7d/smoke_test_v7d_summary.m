function smoke_test_v7d_summary()
%SMOKE_TEST_V7D_SUMMARY 用纯合成的七方法表格验证配对/失败率/结构体。
% 本测试不调用物理仿真或V7d冻结种子，数值不是科研性能。
    config_v7d(); % 加入原V6b bootstrap函数路径
    r=struct();
    r.n_trials=3;
    r.labels={'oracle','independent_sswt','smoothed_sswt', ...
             'static_affine','SAPC','CV_SAPC_V7c','PF_SAPC_V7d'};
    r.success=[true;true;false];
    r.core_rmse=[.10 .40 .45 .30 .25 .27 .24; ...
                 .10 .50 .55 .32 .28 .29 .33; ...
                 NaN NaN NaN NaN NaN NaN NaN];
    r.holdout_rmse=[.01 .40 .45 .32 .27 .29 .26; ...
                    .01 .50 .55 .35 .29 .30 .36; ...
                    NaN NaN NaN NaN NaN NaN NaN];
    r.valid_fraction=[repmat(.9,1,7);repmat(.85,1,7);nan(1,7)];
    r.common_valid_fraction=[.88;.83;NaN];
    r.alpha_v7c=[0;1;NaN];
    r.alpha_v7d=[.5;0;NaN];
    r.cv_folds_v7c=[true;true;false];
    r.cv_folds_v7d=[true;true;false];
    r.full_extra_peak_MHz=[1.0;.5;NaN];
    s=v7d_summarize(r,200,260131);
    assert(s.total==3 && s.n_success==2 && s.failures==1, ...
           'V7d:UnitFailureDenominator','失败试次没有进入分母。');
    assert(numel(s.comparisons)==4 && ...
           strcmp(s.comparisons(4).versus,'CV_SAPC_V7c'), ...
           'V7d:UnitComparison','比较索引或结构体字段有误。');
    expected=mean(r.core_rmse(1:2,6)-r.core_rmse(1:2,7));
    assert(abs(s.comparisons(4).mean_core_gain-expected)<1e-12, ...
           'V7d:UnitPairing','V7c vs V7d Core gain 配对定义错误。');
    assert(s.comparisons(4).wins==1 && s.comparisons(4).losses==1, ...
           'V7d:UnitWins','配对胜负数错误。');
    assert(s.changed_decision_count==2 && ...
           isequal(s.alpha_counts_v7d,[1 0 1 0 0]), ...
           'V7d:UnitAlpha','门控决策/alpha计数错误。');
    assert(all(isfinite(s.comparisons(4).core_CI95)), ...
           'V7d:UnitBootstrap','两条成功配对样本应得到有限CI。');
    r.success(:)=false;
    s0=v7d_summarize(r,200,260131);
    assert(s0.n_success==0 && isempty(s0.comparisons) && ...
           all(isnan(s0.mean_core)), ...
           'V7d:UnitNoSuccess','零成功分支不能假造性能。');
    fprintf('[V7d summary unit] PASS: 7 methods, paired CI, failures, zero-success branch.\n');
end
