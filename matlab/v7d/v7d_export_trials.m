function v7d_export_trials(folder,r)
%V7D_EXPORT_TRIALS 逐试次保存全部成功/失败记录，禁止筛掉退化样本。
    if ~exist(folder,'dir'),mkdir(folder);end
    trial=(1:r.n_trials).';
    T=table(trial,logical(r.success(:)),r.seed_scatter(:), ...
        r.seed_ref(:),r.seed_meas(:), ...
        r.core_rmse(:,2),r.core_rmse(:,4),r.core_rmse(:,5), ...
        r.core_rmse(:,6),r.core_rmse(:,7), ...
        r.holdout_rmse(:,4),r.holdout_rmse(:,5), ...
        r.holdout_rmse(:,6),r.holdout_rmse(:,7), ...
        r.valid_fraction(:,4),r.valid_fraction(:,5), ...
        r.valid_fraction(:,6),r.valid_fraction(:,7), ...
        r.alpha_v7c(:),r.alpha_v7d(:), ...
        r.cv_folds_v7c(:),r.cv_folds_v7d(:), ...
        r.cv_gain_v7c(:),r.cv_gain_v7d(:), ...
        r.full_extra_peak_MHz(:),r.final_extra_peak_MHz(:), ...
        r.final_total_peak_MHz(:),r.common_valid_fraction(:), ...
        r.common_core_count(:),r.common_holdout_count(:), ...
        r.reason_v7c(:),r.reason_v7d(:), ...
        r.failure_id(:),r.failure_reason(:), ...
        'VariableNames',{'trial','success','seed_scatter','seed_ref','seed_meas', ...
        'core_raw','core_affine','core_full','core_v7c','core_v7d', ...
        'holdout_affine','holdout_full','holdout_v7c','holdout_v7d', ...
        'valid_affine','valid_full','valid_v7c','valid_v7d', ...
        'alpha_v7c','alpha_v7d','cv_folds_v7c','cv_folds_v7d', ...
        'cv_gain_v7c','cv_gain_v7d','extra_full_MHz', ...
        'extra_final_MHz','total_final_MHz','common_valid_fraction', ...
        'common_core_count','common_holdout_count', ...
        'reason_v7c','reason_v7d','failure_id','failure_reason'});
    writetable(T,fullfile(folder,'V7d_DEVELOPMENT_trials.csv'));
end
